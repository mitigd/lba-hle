// Little Big Adventure (lba.exe) on dos-hle-kit: the GameInfo and the module wiring.
//
// The seam table is composed from src/seams/ (video, input, sound, timing, settings). Start from
// docs/seam-candidates.md: every function there that touches hardware becomes a seam, with the
// decomp evidence in its `doc`. Run the game, read the `[hw] unseamed hardware access` lines,
// repeat until there are none. See docs/project.md.
#include "hlekit/machine.h"
#include "hlekit/seam.h"
#include "seams/seams.h"

#include <string>
#include <vector>

using namespace hlekit;

int main(int argc, char** argv) {
    GameInfo g;
    g.title = "Little Big Adventure";
    g.exeName = "lba.exe";
    g.functionsCsv = "docs/functions.csv";   // optional: address,name,size labels from any decompiler
    g.loadHigh = true;                        // free conventional memory for BufSpeak
    g.seams = game::seams::All();

    // LBA.CFG names the sound card drivers SETUP.EXE chose. The sound devices are native here, so
    // the file the game reads says so (it is written to the overlay; the game folder's is untouched).
    // Language and the display flags come from config.ini through the read_config seam.
    const std::string cfg =
        "; generated by lba-hle: the sound devices are native, there are no driver files\r\n"
        "MidiDriver: native\r\n"
        "MidiType: GM\r\n"
        "WaveDriver: native\r\n";
    g.generatedFiles["lba.cfg"] = std::vector<uint8_t>(cfg.begin(), cfg.end());
    g.options = game::seams::PortOptions();   // config.ini in the per-user directory

    // Input callbacks are implemented in src/seams/input.cpp. Uncomment each one as the game's
    // handler is translated; setting onMouse also hides the host cursor.
    g.onKey = game::seams::OnKey;
    // g.onMouse = game::seams::OnMouse;
    // g.onPad = game::seams::OnPad;

    return Main(argc, argv, g);
}
